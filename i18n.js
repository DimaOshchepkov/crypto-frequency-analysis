FA.t = function (lang, key, params) {
  const dict = FA.I18N[lang] || FA.I18N.en;
  let str = dict[key] !== undefined ? dict[key] : key;
  if (params) {
    for (const k in params) str = str.split('{' + k + '}').join(params[k]);
  }
  return str;
};
